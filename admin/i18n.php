/* Admin UI i18n. Russian is the source language of the UI; az/en are applied
   by translating the rendered HTML (longest-phrase-first via strtr). */

function admin_lang(): string {
    $l = $_COOKIE['alang'] ?? 'ru';
    return in_array($l, ['ru', 'az', 'en'], true) ? $l : 'ru';
}

function i18n_apply(string $html): string {
    $lang = admin_lang();
    if ($lang === 'ru') return $html;
    return strtr($html, i18n_dict($lang));
}

function i18n_switcher(): string {
    $cur = admin_lang();
    $out = '<span style="display:inline-flex;gap:4px;margin-right:12px;vertical-align:middle">';
    foreach (['az' => 'AZ', 'ru' => 'RU', 'en' => 'EN'] as $code => $label) {
        $style = $code === $cur
            ? 'background:#011640;color:#fff;'
            : 'background:transparent;color:#011640;border:1px solid #cfd8d6;';
        $out .= '<a href="?section=' . e($_GET['section'] ?? 'overview') . '&lang=' . $code . '" '
              . 'style="' . $style . 'padding:5px 10px;border-radius:8px;font-size:12px;font-weight:800;text-decoration:none">' . $label . '</a>';
    }
    return $out . '</span>';
}

